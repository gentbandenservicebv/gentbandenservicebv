export function SeasonIcon({
  season,
  size = 15,
  className = "",
}: {
  season?: string | null;
  size?: number | string;
  className?: string;
}) {
  const norm = (season || "").toUpperCase();
  if (norm === "SUMMER") {
    return <SummerIcon size={size} className={className} />;
  }
  if (norm === "WINTER") {
    return <WinterIcon size={size} className={className} />;
  }
  return <AllSeasonIcon size={size} className={className} />;
}
